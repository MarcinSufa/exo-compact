import { describe, it, expect } from 'vitest';
import { cleanCapturedRecord, isCcCommandWrapperText, isSyntheticApiError, userAuthoredText } from '../core/extractor.js';
import { demoteHeadings } from '../core/seed.js';
import { collectFilePointers } from '../core/file-pointers.js';

describe('S4j: text Claude Code injects is not user or assistant speech', () => {
  it('drops task notifications, caveats, reminders, cross-session messages and interrupts', () => {
    for (const text of [
      '<task-notification>\n<task-id>b1</task-id>\n<summary>Background command "x" completed (exit code 0)</summary>',
      '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>',
      '<system-reminder>\nContents of memory file\n</system-reminder>',
      '<bash-stdout>ok</bash-stdout>',
      'Another Claude session sent a message:\n<agent-message from="a1">done</agent-message>',
      '[Request interrupted by user for tool use]',
    ]) expect(isCcCommandWrapperText(text)).toBe(true);
  });

  it('keeps real user text, including text that only mentions a tag', () => {
    for (const text of ['Never push to main.', 'why does <task-notification> show up in the seed?', '<bash-input>ls</bash-input>']) {
      expect(isCcCommandWrapperText(text)).toBe(false);
    }
  });

  it('recognises API error placeholders', () => {
    expect(isSyntheticApiError("API Error: Opus 5.5's safeguards flagged this message")).toBe(true);
    expect(isSyntheticApiError('The API Error: line in the log came from retries.')).toBe(false);
  });

  it('screenshots that were only viewed are not file pointers', () => {
    const lines = collectFilePointers([{ role: 'assistant', text: '', toolUses: [
      { tool: 'Read', input: { file_path: '/s/shot.png' } },
      { tool: 'Read', input: { file_path: '/s/app.ts' } },
      { tool: 'Write', input: { file_path: '/s/logo.png' } },
    ] }] as never);
    expect(lines.some((line) => line.startsWith('/s/shot.png'))).toBe(false);
    expect(lines.some((line) => line.startsWith('/s/app.ts'))).toBe(true);
    expect(lines.some((line) => line.startsWith('/s/logo.png (edited)'))).toBe(true);
  });

  it('keeps the real prompt that shares a message with injected text (review of 3.10.5)', () => {
    expect(userAuthoredText('<system-reminder>\nmemory\n</system-reminder>\nNever push to main')).toBe('Never push to main');
    expect(userAuthoredText('[Request interrupted by user]\nno, use X instead')).toBe('no, use X instead');
    expect(userAuthoredText('<task-notification>\n<summary>done</summary>\n</task-notification>')).toBe('');
    expect(userAuthoredText('<task-notification>unclosed')).toBe('');
    expect(userAuthoredText('Plain text.')).toBe('Plain text.');
  });

  it('cleans records written by an older capture on read', () => {
    const user = (text: string) => ({ kind: 'user', origin: 'reconcile', producedBy: 's4-capture', sourceHash: 'h', body: { text } }) as never;
    expect(cleanCapturedRecord(user('<task-notification>\n<summary>Background command done</summary>\n</task-notification>'))).toBeUndefined();
    expect(cleanCapturedRecord({ kind: 'assistant_text', origin: 'reconcile', producedBy: 's4-capture', sourceHash: 'h', body: { text: 'API Error: flagged' } } as never)).toBeUndefined();
    expect((cleanCapturedRecord(user('<system-reminder>x</system-reminder>\nUse pnpm.')) as { body: { text: string } }).body.text).toBe('Use pnpm.');
    const kept = user('Use pnpm.');
    expect(cleanCapturedRecord(kept)).toBe(kept);
  });

  it('demotes reply headings but not lines inside code fences', () => {
    expect(demoteHeadings('## Plan\n```bash\n# comment\n```\n# Title\n### Kept')).toBe('### Plan\n```bash\n# comment\n```\n### Title\n### Kept');
  });

  it('round 2 nits: quoted tags mid-sentence stay, info-string fences do not close', () => {
    expect(userAuthoredText('<system-reminder>a</system-reminder><system-reminder>b</system-reminder>\nkeep')).toBe('keep');
    expect(userAuthoredText(`${'<system-reminder>r</system-reminder>'.repeat(60)}\nkeep`)).toBe('keep');
    expect(userAuthoredText(`ok\n${'<task-notification>t</task-notification>'.repeat(60)}`)).toBe('ok');
    expect(userAuthoredText('why does <system-reminder>x</system-reminder> show up?')).toBe('why does <system-reminder>x</system-reminder> show up?');
    expect(demoteHeadings('```\n## a\n```js\n## b\n```\n## c')).toBe('```\n## a\n```js\n## b\n```\n### c');
  });

  it('stays linear on many lines that open an unclosed tag (review of 3.10.6)', () => {
    const started = performance.now();
    expect(userAuthoredText('<system-reminder>\n'.repeat(55000))).toBe('');
    expect(userAuthoredText(`keep\n${'<system-reminder>\n'.repeat(55000)}`).startsWith('keep')).toBe(true);
    expect(performance.now() - started).toBeLessThan(500);
  });
});
