import { SEED_SENTINEL } from './sentinel.js';

/**
 * 3.13.0 (CONTRACT S4m): the seed's user-history section was 83% of all seed tokens in 71 real
 * seeds (tools/seed-noise.mjs), because every captured `user` record went in verbatim: pasted
 * documents, earlier native summaries, task notifications, system reminders. The renderer then
 * trimmed lines from the oldest end, so one long paste could push every real request out. This
 * keeps what the user typed, short, and only the most recent messages; the full text stays in the
 * transcript and in recall.
 *
 * Everything here is linear in the input; pastes and the length cap work on at most `SCAN_MAX_CHARS`
 * (both ends). It runs synchronously inside the compact hook (round 15: a super-linear pass wedged the hooks worker).
 */
export const HISTORY_MAX_MESSAGES = 15;
export const HISTORY_MAX_CHARS = 400;
const HEAD_CHARS = 200;
const TAIL_CHARS = 180;
const PASTE_HEAD_CHARS = 120;
const SCAN_MAX_CHARS = 64 * 1024;

const HARNESS_TAGS = ['system-reminder', 'task-notification', 'local-command-stdout', 'local-command-stderr', 'local-command-caveat'];
const DROP_WHOLE = [
  'This session is being continued from a previous conversation',
  '[Request interrupted by user',
  'Your response above was stopped',
  'Caveat: The messages below were generated by the user while running local commands',
];

// A subagent's final report, framed by the harness: model output delivered as a prompt, never something the user said.
const SUBAGENT_HANDBACK = /^<agent-message\b[^>\n]*>\s*\[Subagent hand-back\]/;
const dropWhole = (start: string): boolean => DROP_WHOLE.some((prefix) => start.startsWith(prefix)) || SUBAGENT_HANDBACK.test(start);

/** Cuts at `end` without leaving half of a surrogate pair (the API rejects lone surrogates). */
function safeSlice(text: string, start: number, end: number): string {
  let from = Math.max(0, start);
  let to = Math.min(text.length, end);
  if (to < text.length && to > 0 && isHigh(text.charCodeAt(to - 1))) to -= 1;
  if (from > 0 && from < text.length && isLow(text.charCodeAt(from))) from += 1;
  return text.slice(from, to);
}
const isHigh = (code: number): boolean => code >= 0xd800 && code <= 0xdbff;
const isLow = (code: number): boolean => code >= 0xdc00 && code <= 0xdfff;

/** A tag's `>` must follow within this many characters on the same line, else it is typed text. */
const TAG_MAX_CHARS = 200;

/** End (index after `>`) of a tag starting at `at` whose name is exactly `name`, or -1. */
function tagEnd(text: string, at: number, prefixLength: number): number {
  const next = text[at + prefixLength];
  if (next !== '>' && next !== ' ' && next !== '/' && next !== '\t') return -1;
  // Searched only inside the window, so a flood of `>`-less tags stays linear.
  const window = text.slice(at, at + TAG_MAX_CHARS + 1);
  const close = window.indexOf('>', prefixLength);
  if (close < 0) return -1;
  // Only `<name>` or `<name attr="v" ...>` count (closing tags too: the host writes
  // `</pasted_content id="...">`); `<name is odd; a > b` is typed text.
  return /^(?:[ \t]+[\w-]+(?:="[^"\n]*")?)*[ \t]*\/?$/.test(window.slice(prefixLength, close)) ? at + close + 1 : -1;
}

/** First `[start, end)` of a tag `<name...>` (or `</name...>` when `closing`) at or after `from`. */
function findTag(text: string, name: string, from: number, closing: boolean): [number, number] | undefined {
  const prefix = closing ? `</${name}` : `<${name}`;
  for (let at = text.indexOf(prefix, from); at >= 0; at = text.indexOf(prefix, at + 1)) {
    const end = tagEnd(text, at, prefix.length);
    if (end >= 0) return [at, end];
  }
  return undefined;
}

/**
 * Replaces each outermost `<name ...>...</name>` block (nesting counted) with `replace(inner)`.
 * An opening tag with no closing tag is removed on its own, never the text after it. Linear: the
 * next opening and closing tags are found once and reused until the scan passes them.
 */
function replaceBlocks(text: string, name: string, replace: (inner: string) => string): string {
  let out = '';
  let cursor = 0;
  let nextOpen = findTag(text, name, 0, false);
  let nextClose = findTag(text, name, 0, true);
  while (nextOpen) {
    const [open, openEnd] = nextOpen;
    let depth = 1;
    let scan = openEnd;
    let block: [number, number] | undefined;
    nextOpen = findTag(text, name, scan, false);
    while (depth > 0) {
      if (nextClose && nextClose[0] < scan) nextClose = findTag(text, name, scan, true);
      if (!nextClose) break;
      if (nextOpen && nextOpen[0] < nextClose[0]) { depth += 1; scan = nextOpen[1]; nextOpen = findTag(text, name, scan, false); continue; }
      depth -= 1;
      if (depth === 0) block = [nextClose[0], nextClose[1]];
      scan = nextClose[1];
    }
    out += text.slice(cursor, open);
    if (!block) { cursor = openEnd; if (nextOpen && nextOpen[0] < cursor) nextOpen = findTag(text, name, cursor, false); continue; }
    out += replace(text.slice(openEnd, block[0]));
    cursor = block[1];
    if (nextOpen && nextOpen[0] < cursor) nextOpen = findTag(text, name, cursor, false);
  }
  return out + text.slice(cursor);
}

function firstBlock(text: string, name: string): string | undefined {
  let found: string | undefined;
  replaceBlocks(text, name, (inner) => { found ??= inner.trim(); return ''; });
  return found;
}

/** A message the host built from a slash command (it starts with a command tag) reads `/name args`. */
function renderCommand(text: string): string {
  if (!text.trimStart().startsWith('<command-')) return text;
  const name = firstBlock(text, 'command-name');
  const args = firstBlock(text, 'command-args') ?? '';
  let rest = text;
  for (const tag of ['command-name', 'command-args', 'command-message']) rest = replaceBlocks(rest, tag, () => ' ');
  return name === undefined ? rest : `${name}${args ? ` ${args}` : ''}\n${rest}`;
}

const squash = (text: string): string => text.split('\n').map((line) => line.replace(/[ \t \r]+/g, ' ').trim()).filter(Boolean).join('\n');

/** One user message as the seed shows it, or `undefined` when nothing the user typed is left. */
export function condenseUserMessage(text: string): string | undefined {
  const body = cleanUserText(text);
  if (body === undefined || body.length <= HISTORY_MAX_CHARS) return body;
  const total = text.length > SCAN_MAX_CHARS ? text.length : body.length;
  return `${safeSlice(body, 0, HEAD_CHARS).trimEnd()} […${total} chars, full text in the transcript…] ${safeSlice(body, body.length - TAIL_CHARS, body.length).trimStart()}`;
}

/** What the user typed, without harness blocks, native summaries, or paste bodies; not length-capped. */
export function cleanUserText(text: string): string | undefined {
  const start = text.trimStart();
  if (!start || start.startsWith(SEED_SENTINEL) || dropWhole(start)) return undefined;
  // Harness blocks go first, on the whole text (the scanner is linear), so a block cut by the
  // window below cannot leave its body behind as if the user typed it.
  let body = start;
  for (const tag of HARNESS_TAGS) body = replaceBlocks(body, tag, () => ' ');
  body = renderCommand(body);
  // A request usually follows a paste, so a huge message keeps both ends.
  if (body.length > SCAN_MAX_CHARS) body = `${safeSlice(body, 0, SCAN_MAX_CHARS / 2)}\n[…]\n${safeSlice(body, body.length - SCAN_MAX_CHARS / 2, body.length)}`;
  body = replaceBlocks(body, 'pasted_content', (inner) => {
    const pasted = squash(inner).replace(/\n/g, ' ');
    const head = pasted.length > PASTE_HEAD_CHARS ? `${safeSlice(pasted, 0, PASTE_HEAD_CHARS).trimEnd()}…` : pasted;
    return `\n[pasted ${pasted.length} chars: ${head}]\n`;
  });
  body = squash(body);
  return body || undefined;
}

/** The most recent `maxMessages` condensed messages, oldest first, repeats of the previous one dropped. */
export function condenseUserHistory(texts: readonly string[], maxMessages: number = HISTORY_MAX_MESSAGES): { messages: string[]; omittedCount: number } {
  const kept: string[] = [];
  for (const text of texts) {
    const message = condenseUserMessage(text);
    if (message === undefined || message === kept[kept.length - 1]) continue;
    kept.push(message);
  }
  const omittedCount = Math.max(0, kept.length - maxMessages);
  return { messages: kept.slice(omittedCount), omittedCount };
}

/** The unquoted line the seed puts above the kept messages when older ones were left out. */
export const historyOmittedNote = (count: number): string => `(${count} earlier user messages not shown; full text in the transcript)`;

/**
 * 3.31.0 (CONTRACT S4ze): a long request (a task brief, a spec) as the user sent it, for the brief file on disk:
 * harness blocks and the slash-command wrapper go, a paste keeps its body (it usually is the brief), line breaks and
 * indentation stay. `undefined` when nothing typed is left. Linear; capped at `BRIEF_MAX_CHARS` (both ends).
 */
export const BRIEF_MAX_CHARS = 200_000;
export function briefText(text: string): string | undefined {
  const start = text.trimStart();
  if (!start || start.startsWith(SEED_SENTINEL) || dropWhole(start)) return undefined;
  let body = start.length > BRIEF_MAX_CHARS ? `${safeSlice(start, 0, BRIEF_MAX_CHARS / 2)}\n[…]\n${safeSlice(start, start.length - BRIEF_MAX_CHARS / 2, start.length)}` : start;
  for (const tag of HARNESS_TAGS) body = replaceBlocks(body, tag, () => '\n');
  body = renderCommand(body);
  body = replaceBlocks(body, 'pasted_content', (inner) => `\n${inner.trim()}\n`);
  body = body.replace(/\n{3,}/g, '\n\n').trim();
  return body || undefined;
}
